document.addEventListener('DOMContentLoaded', async () => {
    const result = parent.document.getElementById('deepl-test-results');
    const assert = (value, message) => { if (!value) throw new Error(message); };
    const turn = () => new Promise(resolve => setTimeout(resolve, 0));
    const get = id => document.getElementById(id);
    try {
        await turn();
        get('apiKey').value = ' test-key:fx\u200b ';
        get('saveApiKey').click();
        await turn();
        assert(translationMock.storage.deeplApiKey === 'test-key:fx', '保存时应清理 Key');
        translationMock.storageError = '模拟存储失败';
        get('saveApiKey').click();
        await turn();
        assert(get('result').textContent.includes('模拟存储失败') && !get('saveApiKey').disabled, '保存失败应报告且恢复按钮');
        translationMock.storageError = null;
        get('targetLang').value = 'JA';
        get('targetLang').dispatchEvent(new Event('change'));
        await turn();
        assert(translationMock.storage.targetLang === 'JA', '语言选择应保存');
        get('sourceText').value = 'Popup text.';
        let respond;
        let request;
        translationMock.respond = (message, callback) => { request = message; respond = callback; };
        get('translateBtn').click(); get('translateBtn').click();
        assert(translationMock.calls.length === 1 && get('translateBtn').disabled, '弹窗应阻止并发');
        assert(request.targetLang === 'JA' && request.apiKey === 'test-key:fx', '应传递所选语言与清理后的Key');
        respond({ success: false, error: '模拟网络失败' });
        await turn();
        assert(get('result').textContent.includes('模拟网络失败') && !get('translateBtn').disabled, '翻译失败可重试');
        translationMock.respond = null;
        get('translateBtn').click();
        await turn();
        assert(get('result').textContent === '译文：Popup text.', '弹窗应经统一服务显示译文');
        get('capturePageBtn').click();
        await turn(); await turn();
        assert(translationMock.pageCaptures[0].tabId === 1, '整页截图应发往当前标签页');
        assert(get('result').textContent.includes('整页截图已生成') && !get('capturePageBtn').disabled, '整页截图完成后提示保存');
        translationMock.pageCaptureResponse = { success: false, error: '无法在此页面截图' };
        get('capturePageBtn').click();
        await turn(); await turn();
        assert(get('result').textContent.includes('无法在此页面截图'), '整页截图失败应提示原因');
        assert(!get('deeplSettings').hidden && get('localSettings').hidden, '默认显示 DeepL 设置');
        assert(get('localModel').value === 'hf.co/mradermacher/Hunyuan-MT-7B-GGUF:Q5_K_M', '填入默认本地模型');
        get('translationProvider').value = 'local';
        get('translationProvider').dispatchEvent(new Event('change'));
        await turn();
        assert(translationMock.storage.translationProvider === 'local', '切换引擎应立即保存');
        assert(get('deeplSettings').hidden && !get('localSettings').hidden, '切换后显示本地模型设置');
        get('localEndpoint').value = ' ftp://bad ';
        get('saveLocal').click();
        await turn();
        assert(get('result').textContent.includes('http://') && translationMock.storage.localEndpoint === undefined, '应拒绝无效地址');
        get('localEndpoint').value = ' http://127.0.0.1:1234/v1/ ';
        get('localModel').value = ' qwen3-8b ';
        get('saveLocal').click();
        await turn();
        assert(translationMock.storage.localEndpoint === 'http://127.0.0.1:1234/v1' && translationMock.storage.localModel === 'qwen3-8b', '保存清理后的本地设置');
        get('testLocal').click();
        await turn(); await turn();
        assert(translationMock.modelTests[0].provider === 'local' && translationMock.modelTests[0].localModel === 'qwen3-8b', '测试连接使用输入框里的设置');
        assert(get('result').textContent.includes('1.2 秒') && get('result').textContent.includes('细节决定成败'), '显示测试译文和耗时');
        get('apiKey').value = '';
        get('sourceText').value = 'Local text.';
        let localRequest;
        translationMock.respond = (message, callback) => { localRequest = message; callback({ success: true, translation: '本地译文' }); };
        get('translateBtn').click();
        await turn();
        assert(get('result').textContent === '本地译文' && localRequest.apiKey === undefined, '本地模型不需要 API Key');
        translationMock.respond = null;
        assert(get('resultMeta').textContent.includes('本地模型 · qwen3-8b'), '译文下方注明引擎和模型');
        get('translationProvider').value = 'openrouter';
        get('translationProvider').dispatchEvent(new Event('change'));
        await turn();
        assert(get('localSettings').hidden && !get('openrouterSettings').hidden && get('deeplSettings').hidden, '切换后只显示 OpenRouter 设置');
        assert(get('openrouterModel').value === 'tencent/hy-mt2-30b-a3b', '填入默认 OpenRouter 模型');
        get('saveOpenrouter').click();
        await turn();
        assert(get('result').textContent.includes('API Key') && translationMock.storage.openrouterApiKey === undefined, '没有 Key 时不能保存');
        get('openrouterApiKey').value = ' sk-or-test\u200b ';
        get('openrouterModel').value = ' qwen/qwen3.8-flash ';
        get('saveOpenrouter').click();
        await turn();
        assert(translationMock.storage.openrouterApiKey === 'sk-or-test' && translationMock.storage.openrouterModel === 'qwen/qwen3.8-flash', '保存清理后的 OpenRouter 设置');
        get('testOpenrouter').click();
        await turn(); await turn();
        const openrouterTest = translationMock.modelTests.at(-1);
        assert(openrouterTest.provider === 'openrouter' && openrouterTest.openrouterApiKey === 'sk-or-test', '测试连接发往 OpenRouter');
        assert(get('result').textContent.includes('$0.000021'), '显示本次花费');
        result.textContent = 'PASS (4)\n弹窗设置、保存失败、语言持久化、请求去重与重试\n整页截图按钮\n翻译引擎切换与本地模型设置\nOpenRouter 设置与测试连接';
        result.dataset.status = 'passed';
    } catch (error) {
        result.textContent = `FAIL: ${error.message}`;
        result.dataset.status = 'failed';
    }
});
